local V,M=PerfTest,CodexInventoryTransferPerformance
V.emit("OnGameStart")
V.check(M.installed and M.enabled,"patch installs with actual Page definitions")
local function setup()
 V.noAction();V.clock=V.clock+1000;V.mouseDown=nil;V.ctrl=false;V.shift=false
 V.player.moving=false
 local p=V.pane(V.container(1000),false)
 V.transfer(p);p.parent:refreshBackpacks()
 return p,p.parent
end
V.case("actual Bottom collapse flushes pending rows and anchors title bar",function()
 local p,page=setup()
 V.change(p,1234);ISInventoryPage.dirtyUI()
 V.eq(p.lastReadCount,1000,"bulk refresh pending before collapse input")
 page:collapseNow()
 V.eq(p.lastReadCount,1234,"collapse input flushes before native geometry")
 V.eq(page.isCollapsed,true,"actual source collapsed")
 V.eq(page.y,401,"Bottom title bar keeps original integer screen Y")
 V.eq(page.height,16,"collapsed real height equals title bar")
 V.eq(page:cleanUIGetContentHeight(),0,"no visible content inside title strip")
 V.eq(p.y,46,"inventory starts below title and search controls")
 V.eq(p.visible,false,"inventory child hidden")
 V.eq(page.controlsUI.visible,false,"search controls hidden")
 V.eq(page.containerButtonPanel.visible,false,"rail hidden")
 page.controlsUI.visible=true -- model a third-party arrange() showing controls again
 page:prerender()
 V.eq(page.controlsUI.visible,false,"reconcile hides auto-shown controls again")
 V.eq(page.y,401,"repeated collapse cannot drift title bar")
end)
V.case("direct vanilla expansion restores frame and exact child visibility",function()
 local p,page=setup()
 page:collapseNow()
 page.isCollapsed=false -- vanilla world-container clicks bypass expandNow
 page:prerender()
 V.eq(page.y,100,"expanded original Y restored")
 V.eq(page.height,317.4,"expanded original height restored")
 V.eq(p.visible,true,"inventory previous visibility restored")
 V.eq(page.controlsUI.visible,true,"search previous visibility restored")
 V.eq(page.containerButtonPanel.visible,false,"previously hidden rail stays hidden")
 V.eq(page._cleanUICollapsedFromBottom,nil,"saved collapse state cleared")
 V.eq(page.maxDrawHeight,nil,"collapsed clipping cleared")
 V.eq(page:cleanUIGetContentHeight(),301,"expanded content stops at integer title boundary")
 V.change(p,2345);ISInventoryPage.dirtyUI();p:onMouseDown(0,0)
 V.eq(p.lastReadCount,2345,"reopened input sees fresh row count")
end)
V.case("collapsed Bottom scale change preserves expanded anchor",function()
 local p,page=setup()
 page:collapseNow();page._cleanUITitleBarScale=2
 page:prerender()
 V.eq(page.height,33,"scaled title height applied")
 V.eq(page.y,384,"scaled title start recomputed from saved expanded frame")
 V.eq(p.visible,false,"scale change keeps inventory hidden")
 page:expandNow()
 V.eq(page.y,100,"explicit expansion original Y restored")
 V.eq(page.height,317.4,"explicit expansion original height restored")
 V.eq(page:cleanUIGetContentHeight(),284,"scaled expanded content reaches title boundary")
end)
V.case("Top title collapse remains native while pending rows flush",function()
 local p,page=setup();page._cleanUITitleBarPosition="top"
 V.change(p,3456);ISInventoryPage.dirtyUI();page:collapseNow()
 V.eq(p.lastReadCount,3456,"Top collapse input flushes pending rows")
 V.eq(page.y,100,"Top title Y unchanged")
 V.eq(page.height,317.4,"Top logical height unchanged")
 V.eq(page._cleanUICollapsedFromBottom,nil,"Top never captures Bottom marker")
 page:expandNow()
 V.eq(page.maxDrawHeight,nil,"Top expansion clears clipping")
end)
return "page Bottom integration passed; cases="..V.cases.."; assertions="..V.assertions
