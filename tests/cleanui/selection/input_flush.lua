local V = PerfTest
V.gameStart()
V.check(CodexInventoryTransferPerformance.installed, "actual 1.2.1 performance wrapper installed")
V.case("pending explicit refresh survives original input chain before next draw", function()
    local p = V.prox({V.item("Apple"), V.item("Bandage"), V.item("Zinc")})
    V.click(p, 1); p:refreshContainer()
    V.click(p, 3, true)
    V.eq(V.selectedCount(p), 3, "Shift input preserves range before next rendered frame")
    p:renderdetails(false)
    V.eq(V.selectedCount(p), 3, "input range survives next draw")
end)
V.case("bulk deferred flush uses actual 1.2.1 reconciliation and input", function()
    local p = V.prox({V.item("Apple"), V.item("Bandage"), V.item("Zinc")})
    V.click(p, 1)
    V.deferNative(p, V.item("Copper"))
    V.click(p, 4, true)
    V.eq(V.selectedCount(p), 4, "input flush keeps original Apple-to-Zinc range")
    V.eq(V.anchorName(p), "Apple", "anchor retained through performance barrier")
    V.check(CodexInventoryTransferPerformance.enabled, "existing optimizer remains enabled")
end)
return V.done()
