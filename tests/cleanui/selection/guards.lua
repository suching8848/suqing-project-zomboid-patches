local V = PerfTest
V.gameStart()
V.case("renderer error restores original selected table and metatable", function()
    local p = V.prox({V.item("Apple"), V.item("Zinc")})
    V.click(p, 1)
    local selected, value = p.selected, p.selected[1]
    p.fixtureRenderError = true
    local ok, err = pcall(p.renderdetails, p, false)
    V.eq(ok, false, "original renderer exception remains visible")
    V.check(tostring(err):find("injected selection render failure", 1, true) ~= nil, "original error retained")
    V.eq(p.selected, selected, "original selected table retained on error")
    V.eq(getmetatable(selected), nil, "temporary metatable removed on error")
    V.eq(selected[1], value, "original raw selected value restored on error")
    p.fixtureRenderError = false; p:renderdetails(false)
    V.eq(p.firstSelect, 1, "next native frame still works")
end)
V.case("unknown selected metatable remains owned by its existing caller", function()
    local p = V.prox({V.item("Apple"), V.item("Zinc")})
    V.click(p, 1)
    local meta = {__index = function(_, key) if key == "sentinel" then return "owner" end end}
    setmetatable(p.selected, meta)
    p.inventory:setDrawDirty(true); p:renderdetails(false)
    V.eq(getmetatable(p.selected), meta, "unknown metatable not replaced")
    V.eq(p.selected.sentinel, "owner", "unknown metatable behavior retained")
    V.eq(p.firstSelect, nil, "unsupported selected table follows original native behavior")
end)
V.case("unchanged render generation leaves native raw selection untouched", function()
    local p = V.prox({V.item("Apple"), V.item("Zinc")})
    V.click(p, 1)
    local selected, value, anchor = p.selected, p.selected[1], p.firstSelect
    local count = SuQingUIInteractionFixes.proximitySelection.stats.restored
    p:renderdetails(false)
    V.eq(p.selected, selected, "plain render keeps table identity")
    V.eq(p.selected[1], value, "plain render keeps exact raw value")
    V.eq(p.firstSelect, anchor, "plain render keeps anchor")
    V.eq(SuQingUIInteractionFixes.proximitySelection.stats.restored, count, "no unnecessary post-render restoration")
end)
V.case("refresh then native mouse-up without reselection retains pending meaning", function()
    local p = V.prox({V.item("Bandage"), V.item("Zinc")})
    V.click(p, 1)
    p.inventory.nativeItems[#p.inventory.nativeItems + 1] = V.item("Apple")
    p:refreshContainer()
    V.shift = true; p:onMouseUp(-1, -1); V.shift = false
    p:renderdetails(false)
    V.eq(V.anchorName(p), "Bandage", "mouse-up keeps semantic anchor")
    V.eq(p.firstSelect, 2, "mouse-up range follows pending row insertion")
    V.eq(p.selected[2], p.items[2], "mouse-up selection follows rendered row")
end)
return V.done()
