function CN.nextChar(s, i)
    if not CN.byteStrings then return i + 1 end
    local b = string.byte(s, i) or 0
    return i + (b < 128 and 1 or (b < 224 and 2 or (b < 240 and 3 or 4)))
end

function CN.popChar(s)
    if not CN.byteStrings then return string.sub(s, 1, #s - 1) end
    local i = #s
    while i > 1 do
        local b = string.byte(s, i)
        if b < 128 or b >= 192 then break end
        i = i - 1
    end
    return string.sub(s, 1, i - 1)
end

function CN.clip(s, font, width)
    s = tostring(s or '')
    local tm = getTextManager()
    if tm:MeasureStringX(font, s) <= width then return s end
    while #s > 0 and tm:MeasureStringX(font, s .. '...') > width do s = CN.popChar(s) end
    return s .. '...'
end

function CN.wrap(s, font, width)
    local lines, cur = {}, ''
    local tm = getTextManager()
    width = math.max(1, width)
    for word in string.gmatch(tostring(s or ''), '%S+') do
        local joined = cur == '' and word or (cur .. ' ' .. word)
        if tm:MeasureStringX(font, joined) <= width then
            cur = joined
        else
            if cur ~= '' then table.insert(lines, cur) end
            while #word > 0 and tm:MeasureStringX(font, word) > width do
                local cut, i = 0, 1
                while i <= #word do
                    local j = CN.nextChar(word, i)
                    if tm:MeasureStringX(font, string.sub(word, 1, j - 1)) > width then
                        if cut == 0 then cut = j - 1 end
                        break
                    end
                    cut, i = j - 1, j
                end
                table.insert(lines, string.sub(word, 1, cut))
                word = string.sub(word, cut + 1)
            end
            cur = word
        end
    end
    if cur ~= '' then table.insert(lines, cur) end
    return lines
end

-- Vanilla ISRichTextPanel only breaks at ASCII spaces. Add measured line commands
-- for this panel's Chinese text; preserve tags, fonts and original text elsewhere.
function CN.richText(s, width, font)
    s = tostring(s or '')
    if not string.find(s, '[^\1-\127]') then return s end
    local out, line, i = {}, '', 1
    local tm = getTextManager()
    font = font or UIFont.Small
    width = math.max(1, width - 8)
    while i <= #s do
        local c = string.sub(s, i, i)
        if c == '<' then
            local e = string.find(s, '>', i, true)
            if e then
                local tag = string.sub(s, i, e)
                table.insert(out, tag)
                if tag == '<LINE>' or tag == '<BR>' then line = '' end
                if tag == '<H1>' then font = UIFont.Large end
                if tag == '<H2>' then font = UIFont.Medium end
                if tag == '<TEXT>' then font = UIFont.Small end
                i = e + 1
            else
                table.insert(out, c); line = line .. c; i = i + 1
            end
        elseif c == '\n' then
            table.insert(out, ' <LINE> '); line = ''; i = i + 1
        else
            local j = CN.nextChar(s, i)
            if string.byte(s, i) < 128 and string.find(c, '[%w_./\\:%-]') then
                while j <= #s and string.find(string.sub(s, j, j), '[%w_./\\:%-]') do j = j + 1 end
            end
            local part = string.sub(s, i, j - 1)
            if line ~= '' and tm:MeasureStringX(font, line .. part) > width then
                table.insert(out, ' <LINE> '); line = ''
            end
            if tm:MeasureStringX(font, part) > width then
                local parts = CN.wrap(part, font, width)
                for k, piece in ipairs(parts) do
                    if k > 1 then table.insert(out, ' <LINE> ') end
                    table.insert(out, piece)
                end
                line = parts[#parts] or ''
            else
                table.insert(out, part); line = line .. part
            end
            i = j
        end
    end
    return table.concat(out)
end

function CN.install()
    if CN.applied or not PzoptSettings or not PzoptOptionSections or not PzoptSettingsLayout then return end
    local p = getPerformance()
    local ok, present = pcall(function() return p:hasPzoptOptions() end)
    if not ok or not present then return end
    local vok, version = pcall(function() return p:getPzoptUpdateInstalledCommit() end)
    if vok and version and version ~= '' and version ~= 'd1bbdcf' then
        print('[CodexPZOptCN] warning: installed engine ' .. tostring(version) .. '; this UI patch targets d1bbdcf. Disable it before updating.')
    end
    local count, tips = 0, 0
    local function translateEntry(e)
        if not e or not e.key then return end
        if CN.labels[e.key] then
            e.codexEnglishLabel = e.label
            e.label = CN.labels[e.key]
            count = count + 1
        end
        if CN.tips[e.key] then e.tip = CN.tips[e.key]; tips = tips + 1 end
        for value, note in pairs(e.note or {}) do
            e.note[value] = CN.notes[note] or CN.ui[note] or note
        end
    end
    for _, page in ipairs(PzoptOptionSections()) do
        for _, section in ipairs(page) do
            -- Keep section.title in English: layout.sections/home use it as a routing key.
            for _, entry in ipairs(section.entries or {}) do translateEntry(entry) end
        end
    end
    for _, entry in ipairs(PzoptSettings.MASTERS or {}) do translateEntry(entry) end
    local function layoutText(t, seen)
        if type(t) ~= 'table' or seen[t] then return end
        seen[t] = true
        for k, v in pairs(t) do
            if type(v) == 'table' then layoutText(v, seen)
            elseif type(v) == 'string' and (k == 'title' or k == 'blurb' or k == 'note' or k == 'cause' or k == 'why') then
                t[k] = CN.ui[v] or v
            end
        end
    end
    layoutText(PzoptSettingsLayout, {})
    for _, axis in ipairs(PzoptSettings.AXES or {}) do axis.label = CN.ui[axis.label] or axis.label end
    PzoptSettings.RESTART_NOTE = CN.strings["s162"]
    PzoptSettings.LIVE_NOTE = CN.strings["s161"]
    PzoptSettings.EXPORT_TITLE = CN.strings["s123"]
    PzoptSettings.IMPORT_TITLE = CN.strings["s195"]
    PzoptSettings.UNINSTALL_TITLE = CN.strings["s194"]
    PzoptSettings.UNINSTALL_TIP = CN.strings["s193"]
    PzoptSettings.UNINSTALL_CONFIRM = CN.strings["s192"]
    local oldCat = PzoptSettings.CATS.entry
    PzoptSettings.CATS.entry = function(cat, live)
        local e = oldCat(cat, live)
        e.label = cat.title .. CN.strings["s191"]
        e.tip = live and CN.strings["s190"]
            or CN.strings["s189"]
        return e
    end
    local oldPresets = PzoptSettings.presets
    PzoptSettings.presets = function(...)
        local list = oldPresets(...)
        for i, entry in ipairs(list) do
            local item = CN.presets[i]
            if item then entry.title, entry.tip = item[1], item[2] end
        end
        return list
    end
    local oldSearch = PzoptSettings.search
    PzoptSettings.search = function(index, query)
        if not string.find(query or '', '[^\1-\127]') then return oldSearch(index, query) end
        local hits, n = {}, 0
        for _, row in ipairs(index.rows or {}) do
            local e = row.entry or {}
            local hay = string.lower((e.label or '') .. ' ' .. (e.tip or '') .. ' ' .. (e.key or '') .. ' '
                .. (row.cat and row.cat.title or '') .. ' ' .. (row.sub and row.sub.title or ''))
            local all, score = true, 0
            for word in string.gmatch(string.lower(query), '%S+') do
                if not string.find(hay, word, 1, true) then all = false; break end
                score = score + 1
                if string.find(e.label or '', word, 1, true) then score = score + 3 end
            end
            if all and score > 0 then hits[row] = score; n = n + 1 end
        end
        return hits, n
    end
    if PzoptPreview and PzoptPreview.text then
        local oldText = PzoptPreview.text
        PzoptPreview.text = function(self, text, ...) return oldText(self, CN.ui[text] or text, ...) end
    end
    CN.applied, CN.labelCount, CN.tipCount = true, count, tips
    print('[CodexPZOptCN] installed: ' .. count .. ' setting labels, ' .. tips .. ' Chinese descriptions; UI only; engine d1bbdcf.')
end

Events.OnGameBoot.Add(CN.install)
